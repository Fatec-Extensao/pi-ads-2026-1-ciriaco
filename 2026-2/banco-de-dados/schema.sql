    NOME VARCHAR2(100) NOT NULL,
    EMAIL VARCHAR2(150) NOT NULL,
    SENHA_HASH VARCHAR2(255) NOT NULL
);

-- 2. Tabela PESQUISA
CREATE TABLE PESQUISA (
    ID_PESQUISA NUMBER PRIMARY KEY,
    TITULO VARCHAR2(200) NOT NULL,
    DATA_INICIAL DATE,
    DATA_FIM DATE,
    ID_GESTOR NUMBER NOT NULL,
    CONSTRAINT FK_PESQUISA_GESTOR
        FOREIGN KEY (ID_GESTOR)
        REFERENCES GESTOR(ID_GESTOR)
);

-- 3. Tabela CATEGORIA
CREATE TABLE CATEGORIA (
    ID_CATEGORIA NUMBER PRIMARY KEY,
    NOME VARCHAR2(100) NOT NULL,
    DESCRICAO VARCHAR2(500)
);

-- 4. Tabela QUESTIONARIO
CREATE TABLE QUESTIONARIO (
    ID_QUESTIONARIO NUMBER PRIMARY KEY,
    ID_PESQUISA NUMBER NOT NULL,
    ID_CATEGORIA NUMBER NOT NULL,
    CONSTRAINT FK_QUESTIONARIO_PESQUISA
        FOREIGN KEY (ID_PESQUISA)
        REFERENCES PESQUISA(ID_PESQUISA),
    CONSTRAINT FK_QUESTIONARIO_CATEGORIA
        FOREIGN KEY (ID_CATEGORIA)
        REFERENCES CATEGORIA(ID_CATEGORIA)
);

-- 5. Tabela PERGUNTA
CREATE TABLE PERGUNTA (
    ID_PERGUNTA NUMBER PRIMARY KEY,
    ENUNCIADO VARCHAR2(500) NOT NULL,
    TIPO_RESPOSTA VARCHAR2(50) NOT NULL,
    ID_QUESTIONARIO NUMBER NOT NULL,
    CONSTRAINT FK_PERGUNTA_QUESTIONARIO
        FOREIGN KEY (ID_QUESTIONARIO)
        REFERENCES QUESTIONARIO(ID_QUESTIONARIO)
);

-- 6. Tabela ALTERNATIVA
CREATE TABLE ALTERNATIVA (
    ID_ALTERNATIVA NUMBER PRIMARY KEY,
    TEXTO VARCHAR2(200) NOT NULL,
    ID_PERGUNTA NUMBER NOT NULL,
    CONSTRAINT FK_ALTERNATIVA_PERGUNTA
        FOREIGN KEY (ID_PERGUNTA)
        REFERENCES PERGUNTA(ID_PERGUNTA)
);

-- 7. Tabela CODIGO_ANONIMO
