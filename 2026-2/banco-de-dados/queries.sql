SELECT A.TEXTO, COUNT(R.ID_RESPOSTA) AS TOTAL_RESPOSTAS
FROM ALTERNATIVA A
LEFT JOIN RESPOSTA R
ON A.ID_ALTERNATIVA = R.ID_ALTERNATIVA
GROUP BY A.TEXTO
ORDER BY A.TEXTO;


SELECT P.ENUNCIADO, COUNT(R.ID_RESPOSTA) AS TOTAL_RESPOSTAS
FROM PERGUNTA P
LEFT JOIN RESPOSTA R
ON P.ID_PERGUNTA = R.ID_PERGUNTA
GROUP BY P.ENUNCIADO
ORDER BY P.ENUNCIADO;


SELECT P.TITULO, COUNT(R.ID_RESPOSTA) AS TOTAL_RESPOSTAS
FROM PESQUISA P
INNER JOIN QUESTIONARIO Q
ON P.ID_PESQUISA = Q.ID_PESQUISA
INNER JOIN PERGUNTA PG
ON Q.ID_QUESTIONARIO = PG.ID_QUESTIONARIO
LEFT JOIN RESPOSTA R
ON PG.ID_PERGUNTA = R.ID_PERGUNTA
GROUP BY P.ID_PESQUISA, P.TITULO
ORDER BY P.TITULO;